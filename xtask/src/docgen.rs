fn render_error_codes() -> String {
    let mut out = header(
        "The wire error-code registry, generated from dli_serve::ErrorCode::ALL: \
         each code, its error class (contract §9), and its cause.",
    );
    out.push_str("# Wire error codes\n\n");
    out.push_str(
        "Every non-success return carries exactly one `code` from this closed set, \
         and each code maps to exactly one of the four error classes — `schema` \
         (the call is malformed), `refused` (refused by principle), `finding` (a \
         graded domain finding), or `internal` (a server defect).\n\n",
    );
    out.push_str("| Code | Class | Cause |\n");
    out.push_str("|---|---|---|\n");
    for &(code, class, cause) in ERROR_ROWS {
        let _ = writeln!(out, "| `{}` | `{class}` | {cause} |", code.wire_name());
    }
    out
}

/// The reserved surface keywords, generated from
/// [`dli_syntax::line_open_keywords`] — the parser's real line-open match arms,
/// the single source of truth for what a declaration line may open with. This is
/// the DL-0016 does-what-it-says surface; a wire/surface rename shows up here as a
/// reviewable doc diff, exactly as `ops.md` does for the wire.
fn render_grammar_keywords() -> String {
    let mut keywords: Vec<&str> = dli_syntax::line_open_keywords().to_vec();
    keywords.sort_unstable();
    let count = keywords.len();
    let mut out = header(&format!(
        "The {count} reserved surface keywords a declaration line may open with, \
         generated from dli_syntax::line_open_keywords() — the DL-0016 does-what-it-says surface."
    ));
    out.push_str("# Grammar keywords\n\n");
    let _ = write!(
        out,
        "De Lore Is reserves **{count}** keywords: the words a declaration line may \
         open with. This set is the surface-v1 vocabulary (`decisions.md` DL-0016, \
         the does-what-it-says pass). A line that opens with anything else is a \
         relation fact of the form `pred(args)` or a diagnostic. Retired spellings \
         (for example `fluent`→`state`, `wheel`→`cycle`, the proof block \
         `ledger`→`proof`, `sort`→`kind`) are **killed forms**: the parser refuses \
         them with a renamed-to diagnostic rather than reading them as keywords.\n\n"
    );
    out.push_str("| Keyword |\n|---|\n");
    for keyword in keywords {
        let _ = writeln!(out, "| `{keyword}` |");
    }
    out
}

/// Walk the executable's Clap graph into `(command path, help line)` rows.
fn cli_commands() -> Vec<(String, String)> {
    fn walk(command: &clap::Command, prefix: &str, rows: &mut Vec<(String, String)>) {
        for child in command.get_subcommands() {
            let path = if prefix.is_empty() {
                child.get_name().to_owned()
            } else {
                format!("{prefix} {}", child.get_name())
            };
            let about = child
                .get_about()
                .map(ToString::to_string)
                .unwrap_or_default();
            rows.push((path.clone(), about));
            if child.get_name() != "help" {
                walk(child, &path, rows);
            }
        }
    }

    let command = deloreis::command();
    let mut rows = Vec::new();
    walk(&command, "", &mut rows);
    rows
}

/// The `deloreis` command reference, derived from the executable's Clap graph.
fn render_cli() -> String {
    let command = deloreis::command();
    let count = command.get_subcommands().count();
    let commands = cli_commands();
    let mut out = header(
        "The deloreis CLI command reference, generated from the executable's \
         Clap command graph.",
    );
    out.push_str("# CLI commands\n\n");
    let _ = write!(
        out,
        "`deloreis` exposes **{count}** top-level subcommands, including Clap's \
         generated `help` command; command groups carry nested operations and \
         generated help paths. Each operation is a rendering over the same engines \
         the `dli.*` worker ops serve. Exit codes are uniform: `0` clean, `1` \
         findings, `2` a usage or operational error.\n\n"
    );
    out.push_str("| Command | Description |\n|---|---|\n");
    for (path, about) in commands {
        let _ = writeln!(out, "| `deloreis {path}` | {about} |");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    #[test]
    fn error_rows_cover_all_codes() {
        let documented: BTreeSet<&str> = ERROR_ROWS
            .iter()
            .map(|(code, ..)| code.wire_name())
            .collect();
        let declared: BTreeSet<&str> = ErrorCode::ALL.iter().map(|code| code.wire_name()).collect();
        assert_eq!(
            documented, declared,
            "the docgen error-class table must cover ErrorCode::ALL exactly"
        );
    }

    #[test]
    fn every_op_has_a_request_and_response_schema() {
        let keys: BTreeSet<String> = dli_serve::contract_schemas()
            .into_iter()
            .map(|(name, _)| name)
            .collect();
        for &op in &Op::ALL {
            let wire = wire_name(op);
            assert!(
                keys.contains(&format!("{wire}.request")),
                "no request schema for {wire}"
            );
            assert!(
                keys.contains(&format!("{wire}.response")),
                "no response schema for {wire}"
            );
        }
        assert_eq!(
            keys.len(),
            Op::ALL.len() * 2,
            "contract_schemas must be exactly one request + one response per op"
        );
    }

    #[test]
    fn pages_render_nonempty_and_stable() {
        for page in pages() {
            let first = (page.render)();
            let second = (page.render)();
            assert_eq!(first, second, "{} render is not deterministic", page.path);
            assert!(first.contains("GENERATED by"), "{} lacks marker", page.path);
            assert!(
                first.starts_with("---\n"),
                "{} lacks frontmatter",
                page.path
            );
        }
    }

    /// The generated page reads the real Clap graph. Keep its command paths
    /// unique and preserve the live/killed proof-command boundary.
    #[test]
    fn cli_metadata_is_closed_and_preserves_killed_forms() {
        let commands = cli_commands();
        let paths: BTreeSet<&str> = commands.iter().map(|(path, _)| path.as_str()).collect();
        assert_eq!(
            paths.len(),
            commands.len(),
            "the Clap graph contains duplicate command paths"
        );
        for (path, about) in &commands {
            assert!(
                !about.trim().is_empty(),
                "the Clap command `{path}` has no help description"
            );
        }
        assert!(
            paths.contains("check-proof"),
            "the DL-0016 `check-proof` command is absent"
        );
        assert!(
            !paths.contains("check-ledger"),
            "the killed `check-ledger` command reappeared"
        );
    }
}

//! Generated reference pages: Markdown committed under `docs/reference-generated`
//! and derived from the crate types, so a wire change is a reviewable doc diff.
//!
//! v0 emits two pages — the operation inventory and the error-code registry.
//! Wave 3 extends the [`pages`] registry (CLI man pages, finding families,
//! grammar); adding a page is one entry there plus its `render` function.

use std::path::Path;

use anyhow::{Context, Result, bail};

use dli_serve::{ErrorCode, Op};

use std::fmt::Write as _;

/// The directory (repo-relative) every generated reference page is written to.
pub const GENERATED_DIR: &str = "docs/reference-generated";

/// A single generated reference page: where it lives and how it renders.
///
/// `render` is a pure function of the crate types — no I/O, no clock — so
/// `docgen` and `docgen --check` share exactly one source of truth.
#[derive(Clone)]
pub struct DocPage {
    /// Repo-relative path, e.g. `docs/reference-generated/ops.md`.
    pub path: &'static str,
    /// The page's fully rendered Markdown, including header and frontmatter.
    pub render: fn() -> String,
}

impl std::fmt::Debug for DocPage {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("DocPage")
            .field("path", &self.path)
            .finish_non_exhaustive()
    }
}

/// The registry of every generated reference page, in write order.
///
/// This is the extension point: a new generated page is one `DocPage` entry
/// with its `render` function. `docgen` writes each page; `docgen --check`
/// re-renders and diffs it against the committed copy.
#[must_use]
pub fn pages() -> Vec<DocPage> {
    vec![
        DocPage {
            path: "docs/reference-generated/ops.md",
            render: render_ops,
        },
        DocPage {
            path: "docs/reference-generated/error-codes.md",
            render: render_error_codes,
        },
        DocPage {
            path: "docs/reference-generated/grammar-keywords.md",
            render: render_grammar_keywords,
        },
        DocPage {
            path: "docs/reference-generated/cli.md",
            render: render_cli,
        },
        DocPage {
            path: "docs/reference-generated/finding-families.md",
            render: crate::finding_families::render,
        },
    ]
}

/// Emit (or, with `check`, verify) every generated reference page.
pub fn run_docgen(root: &Path, check: bool) -> Result<()> {
    let pages = pages();
    if check {
        let mut problems: Vec<String> = Vec::new();
        for page in &pages {
            let rendered = (page.render)();
            let path = root.join(page.path);
            match std::fs::read_to_string(&path) {
                Ok(existing) if existing == rendered => {}
                Ok(_) => problems.push(format!("drift:   {}", path.display())),
                Err(_) => problems.push(format!("missing: {}", path.display())),
            }
        }
        if !problems.is_empty() {
            bail!(
                "docgen --check found {} problem(s); run `cargo run -p xtask -- docgen`:\n{}",
                problems.len(),
                problems.join("\n")
            );
        }
        println!("docgen: {} pages match the committed copies", pages.len());
    } else {
        for page in &pages {
            let path = root.join(page.path);
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent)
                    .with_context(|| format!("creating {}", parent.display()))?;
            }
            std::fs::write(&path, (page.render)())
                .with_context(|| format!("writing {}", path.display()))?;
        }
        println!("docgen: wrote {} pages", pages.len());
    }
    Ok(())
}

/// The generated-file header: YAML frontmatter (repo doc discipline) plus a
/// visible do-not-edit marker. `verdict` is the one-line summary the docs
/// contract requires.
fn header(verdict: &str) -> String {
    format!(
        "---\nstatus: reference\nverdict: \"{verdict}\"\n---\n\n<!-- GENERATED by \
         `cargo run -p xtask -- docgen` — do not edit by hand. Regenerate after any \
         wire change. -->\n\n"
    )
}

/// The wire identifier for an op — its serde rename, the contract's name.
fn wire_name(op: Op) -> String {
    serde_json::to_value(op)
        .ok()
        .and_then(|value| value.as_str().map(str::to_owned))
        .unwrap_or_else(|| format!("{op:?}"))
}

fn render_ops() -> String {
    let count = Op::ALL.len();
    let mut out = header(&format!(
        "The {count}-operation wire inventory, generated from dli_serve::Op::ALL: \
         wire name and request/response payload schema files."
    ));
    out.push_str("# Wire operations\n\n");
    let _ = write!(
        out,
        "The closed operation set: {count} operations. The wire name is each op's \
         serde identifier; its request and response payload schemas live under \
         `contracts/dli-worker/schemas/`. The batch `dli.*` family and the \
         `author.*` Door-T tools are one closed set.\n\n"
    );
    out.push_str("| # | Wire name | Request schema | Response schema |\n");
    out.push_str("|---|---|---|---|\n");
    for (index, &op) in Op::ALL.iter().enumerate() {
        let wire = wire_name(op);
        let _ = writeln!(
            out,
            "| {} | `{wire}` | `{wire}.request.json` | `{wire}.response.json` |",
            index + 1
        );
    }
    out
}

/// The error-code → class → cause mapping (contract §9). The class column is
